/*
 * The package's own build runs the compiled file with Node; nothing imports it,
 * because it is a step and not a module.
 *
 * It is the one place CSS syntax is added: `px` to a length, `ms` to a duration,
 * quotes around a family name, `cubic-bezier()` around a curve, and a colour or
 * a bare number verbatim. The unit therefore lives in exactly one place.
 */
import { writeFile } from 'node:fs/promises';
import path from 'node:path';

import type { Token } from '../types.js';
import { TokenKind } from '../types.js';
import { tokenGroups } from '../values.js';

const outputPath = path.join(import.meta.dirname, '..', 'tokens.css');

function assertNever(value: never): never {
  throw new Error(`Unhandled token: ${String(value)}`);
}

function renderToken(token: Token): string {
  switch (token.kind) {
    case TokenKind.Color:
      return token.value;
    case TokenKind.Length:
      return `${token.value}px`;
    case TokenKind.Duration:
      return `${token.value}ms`;
    case TokenKind.Number:
      return `${token.value}`;
    case TokenKind.Family:
      return `'${token.value}'`;
    case TokenKind.Curve:
      return `cubic-bezier(${token.value.join(', ')})`;
    default:
      return assertNever(token);
  }
}

function renderStylesheet(): string {
  const lines = [
    '/*',
    ' * Generated by @playliberty/tokens. Do not edit.',
    ' * Edit src/values.ts and run the package build.',
    ' */',
    ':root {'
  ];

  for (const [group, tokens] of tokenGroups) {
    lines.push(`  /* ${group} */`);
    for (const [name, token] of Object.entries(tokens)) {
      lines.push(`  --${name}: ${renderToken(token)};`);
    }
  }

  lines.push('}');

  return `${lines.join('\n')}\n`;
}

await writeFile(outputPath, renderStylesheet(), 'utf8');
